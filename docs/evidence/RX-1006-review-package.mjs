assert.equal((await engine.search('original')).total,1);assert.equal((await engine.search('changed')).total,0);
assert.equal((await engine.search({kind:'group',variants:[{text:'atom',match:'prefix'}]})).total,2);
assert.equal((await engine.search('atom')).total,0); assert.equal((await engine.search('😀!!!')).total,0);
const rejected = p => assert.rejects(p, e => e instanceof core.RaveldexError);
await assert.rejects(engine.add(records[1]), e => e.code==='ID_EXISTS');
await assert.rejects(engine.addMany([{id:'new',text:{body:'new'}},{id:'second',text:{body:'duplicate'}}]), e=>e.code==='ID_EXISTS');
