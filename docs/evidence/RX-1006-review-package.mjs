const records = [{id:'__proto__',text:{title:'Original source',body:'atomic batch'},metadata:{kind:'spec'}},{id:'second',text:{title:'Atomic',body:'source'},metadata:{kind:'spec'}}];
const add = engine.addMany(records); const read = engine.search('source'); records[0].text.title='Changed'; records[0].metadata.kind='other';
